def case_clean(tmp: Path) -> tuple[bool, str]:
    corpus = write_corpus(tmp / "corpus", [PAPER_A, PAPER_B])
    out = tmp / "out"
    proc, result = run_pipeline(corpus, out)
    code, report = validate(corpus, out)
    nodes = result["graph"]["stats"]["nodes"]
    edges = result["graph"]["stats"]["edges"]
    ok = proc.returncode == 0 and result["run"]["status"] == "success" and code == 0 and report["verdict"] == "PASS"
    return ok, f"exit={proc.returncode} status={result['run']['status']} nodes={nodes} edges={edges} validate={report['verdict']}"


def case_tampered_quote(tmp: Path) -> tuple[bool, str]:
    corpus = write_corpus(tmp / "corpus", [PAPER_A, PAPER_B])
    draft = tmp / "draft.json"
    draft.write_text(
        json.dumps(
            {
                "entities": [
                    {
                        "source_id": "SYN-A",
                        "paragraph_id": "pa-001",
                        "label": "WS2 monolayer",
                        "entity_type": "material",
                        "quote": "The emission energy of the neutral exciton is 2.99 eV at room temperature",
                    }
                ],
                "relations": [],
            }
        ),
        encoding="utf-8",
    )
    out = tmp / "out"
    proc, result = run_pipeline(corpus, out, draft=draft)
    rejected = len(result["evidence"]["rejected"])
    # one bad entity and nothing else: nothing survives, so the run must refuse rather than invent
    ok = proc.returncode in (1, 5) and rejected == 1 and result["run"]["status"] != "success"
    return ok, f"exit={proc.returncode} status={result['run']['status']} rejected={rejected}"


