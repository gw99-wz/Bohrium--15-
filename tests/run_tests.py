#!/usr/bin/env python3
"""Self-contained regression suite. No network, no third-party packages, no real papers.

Each case builds its own tiny corpus in a temp directory, so the suite proves the pipeline
behaves on inputs the repository does not ship — including the failure paths.

    python tests/run_tests.py            # all cases
    python tests/run_tests.py -k tamper  # one case

A case passes only if the process exit code, the result.json contents and the independent
validator all agree. Exit code 0 = every case passed.
"""

