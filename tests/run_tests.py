def case_single_paper(tmp: Path) -> tuple[bool, str]:
    corpus = write_corpus(tmp / "corpus", [PAPER_A])
    out = tmp / "out"
    proc, result = run_pipeline(corpus, out)
    kinds = {u["kind"] for u in result["uncertainty"]}
    q1 = next(q for q in result["queries"] if q["id"].startswith("Q1"))
    ok = "single_source" in kinds and result["run"]["status"] in ("success", "partial") and q1["answer_count"] == 0
    return ok, f"status={result['run']['status']} warnings={sorted(kinds)} q1_answers={q1['answer_count']}"


def case_unreadable_corpus(tmp: Path) -> tuple[bool, str]:
    tmp.mkdir(parents=True, exist_ok=True)
    empty = tmp / "corpus"
    empty.mkdir()
    out = tmp / "out"
    proc, result = run_pipeline(empty, out)
    ok = proc.returncode == 5 and result["run"]["status"] == "refused" and result["graph"]["nodes"] == []
    return ok, f"exit={proc.returncode} status={result['run']['status']} nodes={len(result['graph']['nodes'])}"


def case_baseline_fails_validation(tmp: Path) -> tuple[bool, str]:
    corpus = write_corpus(tmp / "corpus", [PAPER_A, PAPER_B])
    out = tmp / "out"
    proc, result = run_pipeline(corpus, out, mode="baseline")
    code, report = validate(corpus, out)
    failing = [c["code"] for c in report.get("checks", []) if not c["passed"]]
    ok = proc.returncode == 0 and result["run"]["status"] == "success" and code == 1 and "V12-success-means-verified" in failing
    return ok, f"baseline claims success, validator says {report['verdict']} on {failing}"


def case_contract_fallback(tmp: Path) -> tuple[bool, str]:
    # a case.json with no machine-readable contract must not break the run
    corpus = write_corpus(tmp / "corpus", [PAPER_A, PAPER_B], case={"case_id": "no-contract-case"})
    out = tmp / "out"
    proc, result = run_pipeline(corpus, out)
    ok = (
        proc.returncode == 0
        and result["contract"]["source"] == "fallback"
        and result["contract"]["satisfied"]
        and any("fallback" in l for l in result["run"]["limits"])
    )
    return ok, f"contract_source={result['contract']['source']} satisfied={result['contract']['satisfied']}"


def case_determinism(tmp: Path) -> tuple[bool, str]:
    corpus = write_corpus(tmp / "corpus", [PAPER_A, PAPER_B])
    _, a = run_pipeline(corpus, tmp / "out1")
    _, b = run_pipeline(corpus, tmp / "out2")
    ids_a = sorted(n["id"] for n in a["graph"]["nodes"]) + sorted(e["id"] for e in a["graph"]["edges"])
    ids_b = sorted(n["id"] for n in b["graph"]["nodes"]) + sorted(e["id"] for e in b["graph"]["edges"])
    ok = ids_a == ids_b and len(ids_a) > 0
    return ok, f"{len(ids_a)} ids identical across two runs={ids_a == ids_b}"


def case_must_not_merge(tmp: Path) -> tuple[bool, str]:
    corpus = write_corpus(tmp / "corpus", [PAPER_A, PAPER_B])
    _, result = run_pipeline(corpus, tmp / "out")
    blocked = [b for b in result["alignment"]["blocked"] if b["kind"] == "must_not_merge"]
    levels = sorted({b.get("level") for b in blocked})
    metric_nodes = [n for n in result["graph"]["nodes"] if n["type"] == "metric"]
    cross_metric = [n for n in metric_nodes if len(n["sources"]) > 1]
    ok = bool(blocked) and not cross_metric
    return ok, f"must_not_merge={len(blocked)} levels={levels} cross_paper_metric_nodes={len(cross_metric)}"


CASES = [
    ("clean", case_clean),
    ("tampered_quote", case_tampered_quote),
    ("unknown_locator", case_unknown_locator),
    ("single_paper", case_single_paper),
    ("unreadable_corpus", case_unreadable_corpus),
    ("baseline_fails_validation", case_baseline_fails_validation),
    ("contract_fallback", case_contract_fallback),
    ("determinism", case_determinism),
    ("must_not_merge", case_must_not_merge),
]


def main(argv=None) -> int:
    argv = argv if argv is not None else sys.argv[1:]
    only = None
    if "-k" in argv:
        only = argv[argv.index("-k") + 1]

    # Scratch space lives inside the checkout: the system temp dir is not writable under
    # the workspace file sandbox, and a mkdtemp() directory inherits an ACL that the
    # sandbox cannot write through, so the directory is created with a plain mkdir.
    scratch = ROOT / ".testwork"
    scratch.mkdir(exist_ok=True)
    tmp_root = scratch / f"run-{os.getpid()}-{int(time.time()) % 100000}"
    tmp_root.mkdir(exist_ok=False)
    passed = failed = 0
    try:
        for name, fn in CASES:
            if only and only not in name:
                continue
            work = tmp_root / name
            try:
                ok, detail = fn(work)
            except Exception as exc:  # noqa: BLE001
                ok, detail = False, f"{type(exc).__name__}: {exc}"
            print(f"[{'PASS' if ok else 'FAIL'}] {name:<28} {detail}")
            passed += ok
            failed += not ok
    finally:
        shutil.rmtree(tmp_root, ignore_errors=True)

    print()
    print(f"{passed} passed, {failed} failed")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
