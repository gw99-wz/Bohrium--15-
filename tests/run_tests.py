def write_corpus(dirpath: Path, papers: list[dict], case: dict | None = None) -> Path:
    dirpath.mkdir(parents=True, exist_ok=True)
    manifest = {
        "corpus_id": "synthetic-fixture",
        "synthetic": True,
        "provenance": "generated by tests/run_tests.py — not a real paper",
        "papers": [
            {
                "source_id": p["source_id"],
                "doi": p["doi"],
                "title": p["title"],
                "authors": p["authors"],
                "licence": p["licence"],
                "sha256": "0" * 64,
                "paragraph_count": len(p["paragraphs"]),
                "role": "primary" if i == 0 else "secondary",
            }
            for i, p in enumerate(papers)
        ],
    }
    (dirpath / "corpus-manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    (dirpath / "material.json").write_text(
        json.dumps({"papers": papers}, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    (dirpath / "primary-material.json").write_text(json.dumps(papers[0], ensure_ascii=False, indent=2), encoding="utf-8")
    if len(papers) > 1:
        (dirpath / "secondary-material.json").write_text(
            json.dumps(papers[1], ensure_ascii=False, indent=2), encoding="utf-8"
        )
    (dirpath / "case.json").write_text(
        json.dumps(
            case
            if case is not None
            else {
                "case_id": "syn-case-1",
                "output_contract": {"fields": ["case_id", "graph", "queries", "evidence", "run"]},
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    return dirpath


def run_pipeline(corpus: Path, out: Path, mode: str = "skill", draft: Path | None = None):
    cmd = [PY, str(SCRIPTS / "run_pipeline.py"), "--corpus", str(corpus), "--out", str(out), "--mode", mode]
    case = corpus / "case.json"
    if case.exists():
        cmd += ["--case", str(case)]
    if draft:
        cmd += ["--draft", str(draft)]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")
    result_path = out / "result.json"
    result = json.loads(result_path.read_text(encoding="utf-8")) if result_path.exists() else None
    return proc, result


def validate(corpus: Path, out: Path):
    cmd = [PY, str(SCRIPTS / "validate_result.py"), "--result", str(out / "result.json"), "--corpus", str(corpus), "--json"]
    case = corpus / "case.json"
    if case.exists():
        cmd += ["--case", str(case)]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")
    try:
        report = json.loads(proc.stdout)
    except json.JSONDecodeError:
        report = {"verdict": "FAIL", "raw": proc.stdout + proc.stderr}
    return proc.returncode, report


